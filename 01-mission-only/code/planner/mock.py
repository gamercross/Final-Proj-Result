class MockLLM:
    name = "mock-llm"

    def complete(self, system: str, user: str, *, json_mode: bool = False) -> str:
        if json_mode:
            return self._recommend(user)
        return self._report(user)

    def _recommend(self, prompt: str) -> str:
        m = re.search(r"여행 날짜: (\d{4}-\d{2}-\d{2})", prompt)
        d = date.fromisoformat(m.group(1)) if m else date.today()
        n = re.search(r"정확히 (\d)개|객체, (\d)개", prompt)
        count = int(next(g for g in n.groups() if g)) if n else 1
        picks = SEASONAL[d.month][:count]
        city, weather, events, reason = picks[0]
        data: dict[str, Any] = {
            "recommended_city": city,
            "weather": weather,
            "events": events,
            "reason": reason,
        }
        if count > 1:
            data["recommended_cities"] = [
                {"city": c, "weather": w, "events": e, "reason": r} for c, w, e, r in picks
            ]
        return json.dumps(data, ensure_ascii=False)

    def _report(self, prompt: str) -> str:
        m = re.search(r"여행 날짜: (\d{4}-\d{2}-\d{2})", prompt)
        d = date.fromisoformat(m.group(1)) if m else date.today()
        raw = prompt.split(DATA_BEGIN, 1)[1].split(DATA_END, 1)[0]
        return template_report(d, json.loads(raw))


class MockPlaces:
    name = "mock-places"

    def search_restaurants(self, city: str, size: int = 5) -> list[dict[str, Any]]:
        lat, lng = CITY_CENTER.get(city, (None, None))
        items = []
        for i, (category, suffix) in enumerate(SAMPLE_FOODS[:size]):
            name = f"[예시] {city} {suffix}"
            items.append(
                {
                    "name": name,
                    "address": f"{city} 예시로 {i + 1}길 {10 + i}",
                    "category": category,
                    "category_full": f"음식점 > {category}",
                    "phone": "",
                    "url": f"https://map.kakao.com/?q={quote(city + ' 맛집')}",
                    "x": None if lng is None else round(lng + i * 0.002, 6),
                    "y": None if lat is None else round(lat + i * 0.002, 6),
                    "lat": None if lat is None else round(lat + i * 0.002, 6),
                    "lng": None if lng is None else round(lng + i * 0.002, 6),
                }
            )
        return items
